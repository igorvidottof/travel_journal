import 'dart:io';

import 'storage_service_local.dart';

/// Owns permanent photo files, never the camera/library originals.
class PhotoStorageServiceLocal {
  PhotoStorageServiceLocal(this._storage);

  final StorageServiceLocal _storage;

  String _tripPath(String tripId) {
    if (tripId.isEmpty || tripId == '.' || tripId == '..') {
      throw const FormatException('Invalid trip ID');
    }
    return 'photos/${Uri.encodeComponent(tripId)}';
  }

  /// Reads the trip snapshot directly, avoiding a dependency on the trip queue.
  Future<bool> tripExists(String tripId) async {
    final raw = await _storage.readJson('trips.json');
    if (raw == null) return false;
    if (raw is! Map<String, dynamic> ||
        raw['version'] != 1 ||
        raw['trips'] is! List) {
      throw const FormatException('Invalid trip metadata');
    }
    return (raw['trips'] as List).any(
      (entry) => entry is Map<String, dynamic> && entry['id'] == tripId,
    );
  }

  /// Deletes only the app-owned copy directory, including its metadata.
  /// Missing directories are already clean; failures remain retryable.
  Future<void> deleteTripPhotos(String tripId) async {
    final directory = await _storage.directory(_tripPath(tripId));
    final type = await FileSystemEntity.type(
      directory.path,
      followLinks: false,
    );
    if (type != FileSystemEntityType.notFound) {
      await directory.delete(recursive: true);
    }
  }

  Future<Object?> readMetadata(String tripId) =>
      _storage.readJson('${_tripPath(tripId)}/metadata.json');

  Future<void> writeMetadata(String tripId, Object metadata) =>
      _storage.writeJson('${_tripPath(tripId)}/metadata.json', metadata);

  Future<File> photoFile(String tripId, String fileName) async {
    // Only accept filenames generated by the repository, including on reload.
    if (!RegExp(r'^[a-f0-9]{32}\.[a-z0-9]{1,10}$').hasMatch(fileName)) {
      throw const FormatException('Invalid photo filename');
    }
    final directory = await _storage.directory(_tripPath(tripId));
    return File('${directory.path}/$fileName');
  }

  Future<String> savePhoto(
    String tripId,
    String fileName,
    String sourcePath,
  ) async {
    final destination = await photoFile(tripId, fileName);
    await destination.parent.create(recursive: true);
    // The file becomes visible only after the full copy succeeds.
    final temporary = File('${destination.path}.tmp');
    await File(sourcePath).copy(temporary.path);
    final handle = await temporary.open(mode: FileMode.append);
    try {
      await handle.flush();
    } finally {
      await handle.close();
    }
    await temporary.rename(destination.path);
    return destination.path;
  }

  /// Removes files left by interrupted saves or metadata-first deletions.
  /// Returns false if cleanup must be retried the next time photos are loaded.
  Future<bool> cleanUnusedFiles(String tripId, Set<String> retained) async {
    try {
      final directory = await _storage.directory(_tripPath(tripId));
      if (!await directory.exists()) return true;
      var complete = true;
      await for (final entity in directory.list(followLinks: false)) {
        final name = entity.uri.pathSegments.last;
        final ownedPhoto = RegExp(
          r'^[a-f0-9]{32}\.[a-z0-9]{1,10}(\.tmp)?$',
        ).hasMatch(name);
        if (entity is File && ownedPhoto && !retained.contains(name)) {
          try {
            await entity.delete();
          } on FileSystemException {
            complete = false;
          }
        }
      }
      return complete;
    } on Exception {
      return false;
    }
  }
}
